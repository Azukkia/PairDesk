export const STRINGS = { fr, en };

export function resolveLanguage(setting, locale = '') {
  if (LANGUAGES.includes(setting)) return setting;
  return String(locale).toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export function createTranslator(lang) {
  const table = STRINGS[lang] || STRINGS.en;
  return (key, vars = {}) => {
    const text = table[key] ?? STRINGS.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
  };
}
